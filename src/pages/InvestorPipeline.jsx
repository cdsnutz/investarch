import React, { useEffect, useState } from 'react';
import { base44 } from '@/api/base44Client';
import PageHeader from '@/components/shared/PageHeader';
import { Card } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { Skeleton } from '@/components/ui/skeleton';
import { Textarea } from '@/components/ui/textarea';
import { Button } from '@/components/ui/button';
import { cn } from '@/lib/utils';

const STATUSES = ['not_contacted', 'contacted', 'replied', 'negotiating', 'closed'];
const statusClasses = {
  not_contacted: '',
  contacted: 'bg-secondary text-secondary-foreground border-transparent',
  replied: 'bg-bottle/10 text-bottle border-transparent',
  negotiating: 'bg-bottle text-bottle-foreground border-transparent',
  closed: 'bg-destructive/10 text-destructive border-transparent'
};

export default function InvestorPipeline() {
  const [sources, setSources] = useState(null);
  const [projectNames, setProjectNames] = useState({});
  const [notesId, setNotesId] = useState(null);
  const [notesDraft, setNotesDraft] = useState('');

  useEffect(() => {
    base44.entities.FundingSource.filter({}, { sort: '-created_date', limit: 100 })
      .then((p) => setSources(p.items)).catch(() => setSources([]));
    base44.entities.Project.filter({}, { fields: ['id', 'company_name'], limit: 500 })
      .then((p) => setProjectNames(Object.fromEntries(p.items.map((r) => [r.id, r.company_name])))).catch(() => {});
  }, []);

  const setStatus = async (s, status) => {
    setSources((all) => all.map((x) => (x.id === s.id ? { ...x, outreach_status: status } : x)));
    await base44.entities.FundingSource.update(s.id, { outreach_status: status });
  };
  const saveNotes = async (s) => {
    setSources((all) => all.map((x) => (x.id === s.id ? { ...x, interaction_notes: notesDraft } : x)));
    setNotesId(null);
    await base44.entities.FundingSource.update(s.id, { interaction_notes: notesDraft });
  };

  if (sources == null) {
    return (
      <div className="bg-paper min-h-[calc(100vh-3.5rem)] md:min-h-screen p-6 md:p-12 max-w-6xl mx-auto space-y-8">
        <Skeleton className="h-16 w-64" />
        <Skeleton className="h-96 rounded-md" />
      </div>
    );
  }

  return (
    <div className="bg-paper min-h-[calc(100vh-3.5rem)] md:min-h-screen p-6 md:p-12 max-w-6xl mx-auto space-y-10">
      <PageHeader
        title="Investor Pipeline"
        subtitle="Track every investor interaction, funding-fit rationale, and outreach status generated by the dossier engine."
      />

      {sources.length === 0 ? (
        <Card className="p-12 text-center border-dashed rounded-md">
          <h3 className="font-heading text-xl tracking-tight">Pipeline is empty</h3>
          <p className="text-sm text-muted-foreground mt-2">Run funding drafts on a dossier to populate investor matches.</p>
        </Card>
      ) : (
        <div className="overflow-x-auto">
          <div className="grid grid-cols-5 gap-3 min-w-[960px]">
            {STATUSES.map((status) => {
              const col = sources.filter((s) => (s.outreach_status || 'not_contacted') === status);
              return (
                <div key={status} className="space-y-3">
                  <div className="flex items-center justify-between px-1">
                    <span className="text-[10px] uppercase tracking-[0.18em] text-muted-foreground">{status.replace(/_/g, ' ')}</span>
                    <span className="text-xs text-muted-foreground tabular-nums">{col.length}</span>
                  </div>
                  {col.length === 0 ? (
                    <div className="rounded-md border border-dashed border-border h-16" />
                  ) : (
                    col.map((s) => (
                      <Card key={s.id} className="p-3.5 rounded-md space-y-2">
                        <div className="font-medium text-sm">{s.name}</div>
                        <div className="flex items-center gap-1.5 flex-wrap">
                          <Badge variant="outline" className="text-[10px] uppercase">{s.type || 'investor'}</Badge>
                          {s.stage && <span className="text-[10px] text-muted-foreground">{s.stage}</span>}
                        </div>
                        <div className="text-[10px] text-muted-foreground truncate">{projectNames[s.project_id] || 'Standalone'}</div>
                        {s.alignment_rationale && <p className="text-xs text-muted-foreground line-clamp-3">{s.alignment_rationale}</p>}
                        <select
                          value={s.outreach_status || 'not_contacted'}
                          onChange={(e) => setStatus(s, e.target.value)}
                          className={cn('h-7 w-full rounded border border-input bg-white px-1.5 text-[10px] capitalize')}
                        >
                          {STATUSES.map((st) => <option key={st} value={st}>{st.replace(/_/g, ' ')}</option>)}
                        </select>
                        {notesId === s.id ? (
                          <div className="space-y-1.5">
                            <Textarea rows={3} value={notesDraft} onChange={(e) => setNotesDraft(e.target.value)} className="text-xs" />
                            <div className="flex gap-1.5">
                              <Button size="sm" className="h-6 px-2 text-[10px] bg-bottle hover:bg-bottle/90 text-bottle-foreground" onClick={() => saveNotes(s)}>Save</Button>
                              <Button size="sm" variant="outline" className="h-6 px-2 text-[10px]" onClick={() => setNotesId(null)}>Cancel</Button>
                            </div>
                          </div>
                        ) : (
                          <button
                            onClick={() => { setNotesId(s.id); setNotesDraft(s.interaction_notes || ''); }}
                            className="text-[10px] text-bottle hover:underline text-left w-full"
                          >
                            {s.interaction_notes ? `Notes: ${s.interaction_notes}` : '+ Add interaction note'}
                          </button>
                        )}
                      </Card>
                    ))
                  )}
                </div>
              );
            })}
          </div>
        </div>
      )}
    </div>
  );
}